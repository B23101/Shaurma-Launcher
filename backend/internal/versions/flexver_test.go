package versions

import "testing"

// Тести портують поведінку Prism Launcher ::Version (FlexVer):
// числове порівняння, пре-релізи нижче релізів, appendices ігноруються,
// провідні нулі зрізаються.

func TestCompare(t *testing.T) {
	cases := []struct {
		a, b string
		want int
	}{
		// Числове порівняння (головний випадок для Forge/NeoForge):
		// "1.20.1-47.4.10" > "1.20.1-47.4.9"
		{"1.20.1-47.4.10", "1.20.1-47.4.9", 1},
		{"47.4.10", "47.4.9", 1},
		{"47.4.9", "47.4.10", -1},
		{"21.1.95", "21.1.233", -1},
		{"1.20.1", "1.20", 1},
		{"1.20", "1.20.1", -1},
		// FlexVer порівнює за довжиною числових секцій: "2.0" < "10.0"
		{"2.0", "10.0", -1},
		{"10.0", "2.0", 1},
		{"1.20.10", "1.20.9", 1},
		// Пре-реліз нижче релізу (Prism: "1.20 Pre-Release 1" < "1.20")
		{"1.20 Pre-Release 1", "1.20", -1},
		{"1.20", "1.20 Pre-Release 1", 1},
		{"0.20.0-beta.9", "0.20.0", -1},
		{"0.20.0", "0.20.0-beta.9", 1},
		// Appendices ігноруються ("+build.5" не впливає)
		{"1.20.1+build.5", "1.20.1", 0},
		{"1.20.1", "1.20.1+ignored", 0},
		// Провідні нулі зрізаються
		{"1.007", "1.7", 0},
		{"1.20.1-0047.4.9", "1.20.1-47.4.10", -1},
		// Рівні
		{"1.20.1", "1.20.1", 0},
		{"vanilla", "vanilla", 0},
		{"", "", 0},
		// Текстові компоненти порівнюються текст-порівнянням
		{"fabric-loader-0.16.5-1.20.1", "fabric-loader-0.16.5-1.20.1", 0},
		{"fabric-loader-0.16.5-1.20.1", "fabric-loader-0.16.10-1.20.1", -1},
		{"1.14", "1.14.4", -1},
		{"1.14.4", "1.14", 1},
		// Prism: Fabric/Quilt підтримуються з MC >= 1.14
		{"1.14", "1.14", 0},
		{"1.13.2", "1.14", -1},
		{"1.15", "1.14", 1},
	}
	for _, c := range cases {
		if got := Compare(c.a, c.b); got != c.want {
			t.Errorf("Compare(%q, %q) = %d, want %d", c.a, c.b, got, c.want)
		}
		// Антисиметрія (крім рівних)
		if c.want != 0 {
			if got := Compare(c.b, c.a); got != -c.want {
				t.Errorf("Compare(%q, %q) = %d, want %d (антисиметрія)", c.b, c.a, got, -c.want)
			}
		}
	}
}

func TestSortDesc(t *testing.T) {
	in := []string{"47.4.10", "47.4.9", "47.4.2", "47.4.100", "47.4.10-beta.1", "1.20.1"}
	SortDesc(in)
	// FlexVer: "47.4.10-beta.1" < "47.4.10" (пре-реліз нижче релізу), але
	// > "47.4.9" (числова частина 10 > 9) — те саме, що в Prism.
	want := []string{"47.4.100", "47.4.10", "47.4.10-beta.1", "47.4.9", "47.4.2", "1.20.1"}
	if len(in) != len(want) {
		t.Fatalf("довжина %d != %d", len(in), len(want))
	}
	for i := range want {
		if in[i] != want[i] {
			t.Fatalf("після SortDesc: %v, хотіли %v", in, want)
		}
	}
}
