// console_file.go — вивід Minecraft-сервера у ФАЙЛ, а не в анонімний pipe.
//
// ПРОБЛЕМА (та сама, що вже вирішена для гри — internal/minecraft/console_log.go):
// сервер запускався з cmd.StdoutPipe()/cmd.StderrPipe(), тобто читаючий кінець
// каналу жив УСЕРЕДИНІ процесу лаунчера. Щойно лаунчер завершувався (вихід у
// трей, крах, оновлення), читача не ставало:
//   - усе, що сервер писав далі, губилося;
//   - після перезапуску лаунчер міг «усиновити» PID, але не отримати вивід —
//     консоль показувала лише те, що пощастило знайти в logs/latest.log, і вже
//     не мала ні JVM-виводу до ініціалізації log4j, ні наших SYSTEM-рядків.
//
// РІШЕННЯ: stdout і stderr дитини — це ФАЙЛ logs/shaurma-console.log. Дескриптор
// успадковується java-процесом і лишається валідним, навіть коли батько помер.
// Лаунчер читає цей файл «хвостом» (followLogFile):
//   - у живому запуску — з початку файлу;
//   - після перезапуску — той самий файл: спершу історія (усе, що сервер
//     написав, поки лаунчера не було), далі стеження за новими рядками.
//
// Файл перезаписується на кожному новому запуску сервера: історія старих
// запусків і так лежить у logs/latest.log (його пише сам сервер).
//
// ВВІД КОМАНД це не лікує: stdin лишається анонімним pipe, який належить
// лаунчеру. Після перезапуску команди недоступні — для них потрібен окремий
// хост-процес (див. коментар у recover.go).
package servers

import (
	"os"
	"path/filepath"
)

// ServerConsoleLogName — ім'я файлу з виводом сервера в logs/ його теки.
// Окремо від latest.log (його пише сам сервер): це службовий канал
// лаунчер↔сервер, який існує ЗАВЖДИ, незалежно від налаштувань логування ядра.
const ServerConsoleLogName = "shaurma-console.log"

// serverConsoleLogPath — шлях до файлу виводу сервера за текою сервера.
func serverConsoleLogPath(dir string) string {
	return filepath.Join(dir, "logs", ServerConsoleLogName)
}

// openServerConsoleLog створює (перезаписуючи) файл виводу сервера і повертає
// його для cmd.Stdout/cmd.Stderr. os/exec для *os.File НЕ створює pipe і
// горутину-копіювальник — дескриптор дублюється безпосередньо в дочірній
// процес, тому запис іде навіть коли лаунчера вже немає.
func openServerConsoleLog(dir string) (*os.File, error) {
	p := serverConsoleLogPath(dir)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return nil, err
	}
	// O_APPEND: stdout і stderr — той самий *os.File для обох, тож порядок
	// рядків зберігається таким, яким його вивів сервер. O_TRUNC — новий
	// запуск починає файл з нуля (консоль теж очищується).
	return os.OpenFile(p, os.O_CREATE|os.O_WRONLY|os.O_TRUNC|os.O_APPEND, 0o644)
}
