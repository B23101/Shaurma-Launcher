package main

import "time"

// ui_ready.go — сигнал «фронтенд змонтовано, можна показувати вікно».
//
// Головне вікно створюється НЕпоказаним (shell/updater_phase.go): воно
// прозоре заради заокруглених кутів, тож показане до першого малювання
// сторінки просвічувало робочий стіл. Фронтенд кличе UIReady одразу після
// mount() — і лише тоді shell показує вікно (і знімає splash). Якщо сигнал
// не прийшов, shell сам покаже вікно за запасним таймером.
//
// ФОНОВИЙ СТАРТ (--background, startupMode=background): вікно НЕ
// показуємо — лише піднімаємо трей, щоб лаунчер було видно в системі й
// його можна було відкрити. Фронтенд при цьому вже змонтований і працює
// (чати, друзі, сповіщення), просто вікно сховане.
//
// Повторні виклики безпечні (Show на вже показаному вікні — no-op).
func (a *App) UIReady() {
	a.notifyRestartedAfterCrash()
	if consumeBackgroundStart() {
		a.ensureTray()
		// Фоновий старт (автозавантаження ОС): вікно не показується і може
		// висіти в треї годинами. Саме цей випадок найдорожчий за пам'яттю -
		// WebView2-процеси вже підняті й тримають сотні мегабайт, хоч UI
		// ніхто не бачить.
		//
		// Тому через backgroundTrimDelay віддаємо ОС робочі набори
		// (memtrim.go: trimNowForHiddenWindow). Не одразу: фронтенд щойно
		// змонтувався і довантажує збірки/іконки — трим у цю мить
		// змусив би його одразу вивантажувати ті ж сторінки назад.
		time.AfterFunc(backgroundTrimDelay, trimNowForHiddenWindow)
		return
	}
	bridgeWindowOp("main", "show")
}

// backgroundTrimDelay — скільки чекати після монтування UI перед першим
// тримом у фоновому старті: стартовий шум (список збірок, іконки, оновлення)
// стихає швидше, а чекати довше — марно тримати сторінки в пам'яті.
const backgroundTrimDelay = 45 * time.Second
