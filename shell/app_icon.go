package main

// app_icon.go — власна іконка ЗАСТОСУНКУ (App.SetIcon), а не лише іконка
// конкретного вікна (window_icon.go/window_icon_linux.go).
//
// ПЛАТФОРМИ, ДЕ ЦЕ РЕАЛЬНО ПРАЦЮЄ: macOS і Windows. Там App.SetIcon(icon
// []byte) — кросплатформений метод Wails v3, доступний одразу після
// application.New, і там дійсно вирішує задачу "іконка застосунку в
// Dock/таскбарі відрізняється від .exe/.app ресурсу".
//
// НА LINUX ЦЕЙ ВИКЛИК — NO-OP (нічого не робить), і appicon.png тут
// ЖОДНОГО ЕФЕКТУ НЕ МАЄ. Це заплутувало раніше: попередня версія цього
// коментаря стверджувала, що SetIcon "вирішує" проблему таскбару на
// Linux — це було правдою лише для GTK3-збірки (там setIcon реально
// викликає gtk_window_set_icon, який існує в GTK3). Wails v3 з версії
// весни 2026 (build docs/FAQ) за замовчуванням збирає Linux-шелл на
// GTK4 + WebKitGTK 6.0 (legacy -tags gtk3 лишається опцією лише до
// v3.1, і цей проєкт таким тегом НЕ збирається — див. grep по Taskfile).
// GTK4 прибрав усі програмні API іконок вікна (gtk_window_set_icon
// видалено), тож на GTK4 setIcon у wails v3 — навмисний no-op.
//
// РЕАЛЬНЕ РІШЕННЯ ДЛЯ LINUX — інший механізм, у ІНШИХ файлах:
// application-id застосунку (Options.Name → org.wails.<...>, див.
// app_identity.go) мусить збігатися з іменем .desktop-файлу, який
// launcherbuild кладе в пакет (desktopid.go) — САМЕ звідти Wayland/X11
// бере Icon= для таскбара/доку/таск-менеджера. applyAppIcon(app)
// викликається в main.go БЕЗУМОВНО на всіх платформах просто тому, що
// на Linux виклик нешкідливий (no-op), а розгалужувати виклик по
// платформах заради економії одного виклику функції сенсу не має.
//
// //go:embed — файл маленький (сотні КБ) і НЕ входить у "великий" контент
// (фронтенд/бекенд/апдейтер), який свідомо не вбудовується в бінарник
// (щоб shell не перекомпілювався при їхній зміні, див. коментар на
// початку assetfs.go) — appicon.png взагалі не змінюється між релізами
// незалежно від фронтенду, тому embed тут доречний і не суперечить цій
// архітектурі.

import (
	_ "embed"

	"github.com/wailsapp/wails/v3/pkg/application"
)

//go:embed appicon.png
var appIconPNG []byte

// applyAppIcon встановлює іконку застосунку одразу після application.New.
// На Linux (GTK4) — no-op, справжнє джерело іконки таскбара там інше
// (app_identity.go/desktopid.go), див. коментар вище. Якщо з якоїсь
// причини App ще не готовий (не мало б статись — викликається синхронно
// з тим самим *App, що повернув New) — тихо виходимо, це не критична для
// роботи лаунчера дія.
func applyAppIcon(app *application.App) {
	if app == nil || len(appIconPNG) == 0 {
		return
	}
	app.SetIcon(appIconPNG)
}
