let currentLang = $state<Lang>(defaultLanguage)

/** Викликати при завантаженні налаштувань: setLanguage(settings.language). */
export function setLanguage(lang: string) {
  if (lang === 'auto') {
    const nav = (navigator.language || '').toLowerCase()
    lang = nav.startsWith('uk') ? 'uk' : 'en'
  }
  currentLang = lang in dictionaries ? (lang as Lang) : defaultLanguage
}

/** Поточна мова (read-only; змінюється лише через setLanguage). */
export function getLanguage(): Lang {
  return currentLang
}

/**
 * Переклад за ключем. Невідомі ключі та мови безпечно відвалюються:
 * ключ повертається як є, а відсутні мови падають на defaultLanguage.
 * params підставляються у {placeholders}.
 */
export function t(key: string, params?: Record<string, string | number>): string {
  const dict = dictionaries[currentLang] ?? dictionaries[defaultLanguage]
  let s = dict[key] ?? key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split(`{${k}}`).join(String(v))
    }
  }
  return s
}
